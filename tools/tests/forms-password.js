// Form filling and password-protected PDFs.
test(async () => {
  await ensurePdfLib();
  const d = await PDFLib.PDFDocument.create();
  const page = d.addPage([595, 842]);
  const form = d.getForm();
  form.createTextField('name').addToPage(page, { x: 50, y: 700, width: 220, height: 22 });
  form.createCheckBox('agree').addToPage(page, { x: 50, y: 660, width: 16, height: 16 });
  const rg = form.createRadioGroup('size'); rg.addOptionToPage('S', page, { x: 50, y: 620, width: 16, height: 16 }); rg.addOptionToPage('M', page, { x: 90, y: 620, width: 16, height: 16 });
  const dd = form.createDropdown('city'); dd.addOptions(['Vilnius', 'Kaunas']); dd.addToPage(page, { x: 50, y: 570, width: 140, height: 22 });
  await loadFiles([new File([await d.save()], 'form.pdf', { type: 'application/pdf' })], false);
  await sleep(1500);
  const q = s => document.querySelector(s);
  check('all 5 form fields are shown', document.querySelectorAll('.ff').length === 5, document.querySelectorAll('.ff').length);
  const name = q('.ff[data-field$="|name"]'); name.value = 'Jonas Ąžuolaitis'; name.dispatchEvent(new Event('input'));
  q('.ff[data-field$="|agree"]').click();
  const radios = [...document.querySelectorAll('.ff[data-field$="|size"]')];
  check('both radio buttons are shown', radios.length === 2, radios.length);
  radios[1].click();
  const city = q('.ff[data-field$="|city"]'); city.value = 'Kaunas'; city.dispatchEvent(new Event('change'));
  const res = await buildPdf(S.pages);
  const back = (await PDFLib.PDFDocument.load(res.bytes)).getForm();
  check('text field saved', back.getTextField('name').getText() === 'Jonas Ąžuolaitis', back.getTextField('name').getText());
  check('checkbox saved', back.getCheckBox('agree').isChecked() === true);
  check('radio choice saved', back.getRadioGroup('size').getSelected() === 'M', back.getRadioGroup('size').getSelected());
  check('dropdown saved', String(back.getDropdown('city').getSelected()) === 'Kaunas', back.getDropdown('city').getSelected());

  const p = await PDFLib.PDFDocument.create();
  p.addPage([595, 842]).drawText('Secret page', { x: 50, y: 760, size: 24 });
  p.encrypt({ userPassword: 'abc', ownerPassword: 'owner123' });
  const enc = await p.save();
  dirty = false;
  const opening = loadFiles([new File([enc], 'secret.pdf', { type: 'application/pdf' })], false);
  await sleep(900);
  check('password is asked for', q('#pwDlg').open);
  q('#pwInput').value = 'wrong'; q('#pwOk').click();
  await sleep(700);
  check('wrong password is refused with a message', q('#pwDlg').open && q('#pwMsg').textContent.length > 0, q('#pwMsg').textContent);
  q('#pwInput').value = 'abc'; q('#pwOk').click();
  await opening;
  check('protected file opens with the right password', S.pages.length === 1, S.pages.length);
  S.pages[0].annots.push({ id: nid(), type: 'text', x: 60, y: 120, text: 'Signed', size: 16, color: '#000000', rot: 0 });
  const saved = await buildPdf(S.pages, { flatten: true });
  const chk = await pdfjsLib.getDocument({ data: saved.bytes.slice(), password: 'abc' }).promise;
  const text = (await (await chk.getPage(1)).getTextContent()).items.map(i => i.str).join(' ');
  check('protected file saves with original and new text', text.includes('Secret page') && text.includes('Signed'), text);
});
